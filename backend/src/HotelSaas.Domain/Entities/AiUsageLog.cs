using HotelSaas.Domain.Common;

namespace HotelSaas.Domain.Entities;

/// <summary>
/// Tracks usage of AI features for billing, auditing, and analytics purposes.
/// </summary>
public class AiUsageLog : BaseEntity, ITenantScopedEntity
{
    /// <summary>
    /// Foreign key to the tenant this usage log belongs to.
    /// </summary>
    public Guid TenantId { get; set; }

    /// <summary>
    /// Optional foreign key to the user who initiated the AI request.
    /// </summary>
    public Guid? UserId { get; set; }

    /// <summary>
    /// Navigation property to the user who initiated the request.
    /// </summary>
    public User? User { get; set; }

    /// <summary>
    /// AI feature used (e.g., "Concierge", "DynamicPricing", "NarrativeReport").
    /// </summary>
    public string Feature { get; set; } = string.Empty;

    /// <summary>
    /// The prompt or input sent to the AI model.
    /// </summary>
    public string Prompt { get; set; } = string.Empty;

    /// <summary>
    /// The response returned by the AI model.
    /// </summary>
    public string Response { get; set; } = string.Empty;

    /// <summary>
    /// Identifier of the AI model used (e.g., "gpt-4o", "gemini-2.5-pro").
    /// </summary>
    public string ModelUsed { get; set; } = string.Empty;

    /// <summary>
    /// Number of input tokens consumed by the request.
    /// </summary>
    public int InputTokens { get; set; }

    /// <summary>
    /// Number of output tokens generated by the response.
    /// </summary>
    public int OutputTokens { get; set; }

    /// <summary>
    /// Total duration of the AI request in milliseconds.
    /// </summary>
    public int DurationMs { get; set; }

    /// <summary>
    /// Whether the AI request completed successfully.
    /// </summary>
    public bool IsSuccess { get; set; }
}
